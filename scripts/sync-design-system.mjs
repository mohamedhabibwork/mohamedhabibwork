// Copies the MH design system (brand/) into the app: compiled tokens.css, component CSS,
// fonts and brand assets under public/brand. Run after changing the design system:
//   node scripts/sync-design-system.mjs
import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ds = join(root, "brand/design-system/project");
const out = join(root, "src/design-system");
const pub = join(root, "public/brand");

const tokens = JSON.parse(readFileSync(join(ds, "tokens.json"), "utf8"));
const themes = tokens.color.themes.map((t) => t.id);
const css = (v) => {
	const m = /^\{(.+)\}$/.exec(v);
	return m ? `var(--${m[1]})` : v;
};
const valueFor = (token, theme, first) => {
	if (typeof token.value === "string") return first ? token.value : undefined;
	return token.value[theme];
};

const blocks = themes.map((theme, i) => {
	const sel = i === 0 ? `:root, [data-theme="${theme}"]` : `[data-theme="${theme}"]`;
	const lines = [];
	for (const fam of ["color", "shadow"]) {
		for (const t of tokens[fam].tokens) {
			const v = valueFor(t, theme, i === 0);
			if (v !== undefined) lines.push(`  --${t.name}: ${css(v)};`);
		}
	}
	return `${sel} {\n  color-scheme: ${theme};\n${lines.join("\n")}\n}`;
});
const rootVars = [];
for (const fam of ["spacing", "radius", "zIndex"]) {
	for (const t of tokens[fam].tokens) rootVars.push(`  --${t.name}: ${t.value};`);
}
for (const [k, v] of Object.entries(tokens.type.families)) rootVars.push(`  --font-${k}: ${v};`);
blocks.push(`:root {\n${rootVars.join("\n")}\n}`);
for (const f of tokens.type.fonts) {
	const file = f.file.split("/").pop();
	const range = file.includes("arabic") ? "\n  unicode-range: U+0600-06FF, U+0750-077F, U+FB50-FDFF, U+FE70-FEFF;" : "";
	blocks.push(`@font-face {\n  font-family: "${f.family}";\n  src: url("/brand/fonts/${file}") format("woff2");\n  font-weight: ${f.weight};\n  font-display: swap;${range}\n}`);
}

mkdirSync(out, { recursive: true });
writeFileSync(join(out, "tokens.css"), `/* Generated by scripts/sync-design-system.mjs from brand/design-system/project/tokens.json. Do not edit. */\n${blocks.join("\n\n")}\n`);
cpSync(join(ds, "components/bundle.css"), join(out, "components.css"));

mkdirSync(pub, { recursive: true });
cpSync(join(ds, "fonts"), join(pub, "fonts"), { recursive: true });
cpSync(join(root, "brand/icons"), join(pub, "icons"), { recursive: true });
cpSync(join(root, "brand/images"), join(pub, "images"), { recursive: true });
cpSync(join(root, "brand/templates"), join(pub, "templates"), { recursive: true });
mkdirSync(join(pub, "marks"), { recursive: true });
for (const f of ["mh-mark.svg", "mh-mark-black.svg", "mh-mark-white.svg", "mh-lockup-dark.svg", "mh-lockup-light.svg"]) {
	cpSync(join(root, "brand/logo/svg", f), join(pub, "marks", f));
}
cpSync(join(root, "brand/logo/favicon"), join(root, "public"), { recursive: true });
console.log("design system synced →", out, "and", pub);
